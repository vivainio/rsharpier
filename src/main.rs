use clap::{Args, Parser, Subcommand, ValueEnum};

use csharpier_rs::cli::{self, CommandLineOptions, LogFormat, LogLevel};

#[derive(Parser)]
#[command(name = "rsharpier", version, about = "An opinionated C# formatter")]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Clone, Copy, ValueEnum)]
enum LogFormatArg {
    Console,
    #[value(name = "MsBuild")]
    MsBuild,
}

#[derive(Clone, Copy, ValueEnum)]
enum LogLevelArg {
    Trace,
    Debug,
    Information,
    Warning,
    Error,
    Critical,
    None,
}

#[derive(Args)]
struct Common {
    /// One or more paths to a directory containing files to format or a specific file to format.
    /// May be omitted when piping data via stdin.
    #[arg(value_name = "directoryOrFile")]
    paths: Vec<String>,
    /// Path to the CSharpier configuration file
    #[arg(long)]
    config_path: Option<String>,
    /// Path to the CSharpier ignore file
    #[arg(long)]
    ignore_path: Option<String>,
    /// Log output format
    #[arg(long, value_enum, default_value = "console", ignore_case = true)]
    log_format: LogFormatArg,
    /// Specify the log level
    #[arg(long, value_enum, default_value = "information", ignore_case = true)]
    log_level: LogLevelArg,
    /// Include files generated by the SDK and files that begin with <autogenerated /> comments
    #[arg(long)]
    include_generated: bool,
    /// Bypass the check to determine if a csproj files references a different version of CSharpier.MsBuild.
    #[arg(long)]
    no_msbuild_check: bool,
    /// Treat syntax errors from files as warnings instead of errors.
    #[arg(long)]
    syntax_errors_as_warnings: bool,
}

#[derive(Subcommand)]
enum Command {
    /// Format files.
    Format {
        #[command(flatten)]
        common: Common,
        /// Bypass the cache to determine if a file needs to be formatted.
        #[arg(long)]
        no_cache: bool,
        /// Skip validation of formatted files to improve performance.
        #[arg(long)]
        skip_validation: bool,
        /// Skip writing changes.
        #[arg(long)]
        skip_write: bool,
        /// Write the results of formatting any files to stdout.
        #[arg(long)]
        write_stdout: bool,
        /// Supply a path when piping input to format via stdin
        #[arg(long)]
        stdin_path: Option<String>,
    },
    /// Check that files are formatted. Will not write any changes.
    Check {
        #[command(flatten)]
        common: Common,
        /// Use the cache to determine if a file needs to be formatted.
        #[arg(long)]
        use_cache: bool,
        /// Treat unformatted files as warnings instead of errors.
        #[arg(long)]
        unformatted_as_warnings: bool,
    },
    /// Keep rsharpier running so that multiples files can be piped to it via stdin.
    PipeFiles,
    /// Run rsharpier as a server so that multiple files may be formatted.
    Server {
        /// Specify the port that rsharpier should start on. Defaults to a random unused port.
        #[arg(long)]
        server_port: Option<u16>,
    },
}

fn common_options(c: Common) -> CommandLineOptions {
    CommandLineOptions {
        paths: c.paths,
        config_path: c.config_path,
        ignore_path: c.ignore_path,
        include_generated: c.include_generated,
        syntax_errors_as_warnings: c.syntax_errors_as_warnings,
        log_format: match c.log_format {
            LogFormatArg::Console => LogFormat::Console,
            LogFormatArg::MsBuild => LogFormat::MsBuild,
        },
        log_level: match c.log_level {
            LogLevelArg::Trace => LogLevel::Trace,
            LogLevelArg::Debug => LogLevel::Debug,
            LogLevelArg::Information => LogLevel::Information,
            LogLevelArg::Warning => LogLevel::Warning,
            LogLevelArg::Error => LogLevel::Error,
            LogLevelArg::Critical => LogLevel::Critical,
            LogLevelArg::None => LogLevel::None,
        },
        ..Default::default()
    }
}

fn main() {
    let cli = Cli::parse();
    let options = match cli.command {
        Command::PipeFiles => std::process::exit(cli::pipe_files()),
        Command::Server { server_port } => std::process::exit(cli::server::run_server(server_port)),
        Command::Format { common, skip_validation, skip_write, write_stdout, stdin_path, .. } => CommandLineOptions {
            skip_validation,
            skip_write,
            write_stdout,
            stdin_path,
            ..common_options(common)
        },
        Command::Check { common, unformatted_as_warnings, .. } => CommandLineOptions {
            check: true,
            unformatted_as_warnings,
            ..common_options(common)
        },
    };
    std::process::exit(cli::run(options));
}
