#[test]
fn format_gets_line_endings_from_the_code() {
    for eol in ["\n", "\r\n"] {
        let r = format(&format!("public class ClassName {{{eol}}}"));
        assert_eq!(r.code, format!("public class ClassName {{ }}{eol}"));
    }
}

// ---- LineEndingTests ----

fn width_80(eol: EndOfLine) -> CodeFormatterOptions {
    CodeFormatterOptions { width: 80, end_of_line: eol, ..Default::default() }
}

#[test]
fn line_endings_do_not_affect_output_with_verbatim_string() {
    // a verbatim string that is just the right size to format differently with \n vs \r\n
    let code = "class ClassName\n{\n    private string blah = @\"one11111111111111111111111111111111\ntwo\nthree\nfour\";\n}\n";
    let lf = CSharpFormatter::format(code, &width_80(EndOfLine::Auto));
    let crlf = CSharpFormatter::format(&code.replace('\n', "\r\n"), &width_80(EndOfLine::Auto));
    assert_eq!(lf.code, crlf.code.replace("\r\n", "\n"));
}

#[test]
fn line_endings_do_not_affect_output_with_interpolated_string() {
    let code = "class ClassName\n{\n    private string blah = @$\"one1111111111111111111111111111111\ntwo\nthree\nfour\";\n}\n";
    let lf = CSharpFormatter::format(code, &width_80(EndOfLine::Auto));
    let crlf = CSharpFormatter::format(&code.replace('\n', "\r\n"), &width_80(EndOfLine::Auto));
    assert_eq!(lf.code, crlf.code.replace("\r\n", "\n"));
}

#[test]
fn line_endings_in_verbatim_string_respect_options() {
    for (new_line, eol) in [("\r\n", EndOfLine::Lf), ("\n", EndOfLine::Crlf)] {
        let code = format!("class ClassName\n{{\n    string value = @\"one{new_line}two\";\n}}\n");
        let r = CSharpFormatter::format(&code, &CodeFormatterOptions { end_of_line: eol, ..Default::default() });
        assert!(!r.code.contains(&format!("one{new_line}two")), "{:?}", r.code);
    }
}

#[test]
fn ignored_range_in_separated_list_respects_line_ending() {
    for eol in [EndOfLine::Lf, EndOfLine::Crlf] {
        let code = "var value = new()\n{\n    // csharpier-ignore-start\n    First =     1,\n    Second =     2\n    // csharpier-ignore-end\n};\n";
        let r = CSharpFormatter::format(code, &CodeFormatterOptions { end_of_line: eol, ..Default::default() });
        let expected = if eol == EndOfLine::Lf { code.to_string() } else { code.replace('\n', "\r\n") };
        assert_eq!(r.code, expected);
    }
}

#[test]
fn escaped_line_endings_in_verbatim_string_remain() {
    for (escaped, eol) in [("\\r\\n", EndOfLine::Lf), ("\\n", EndOfLine::Crlf)] {
        let code = format!("class ClassName\n{{\n    string value = @\"one{escaped}two\";\n}}\n");
        let r = CSharpFormatter::format(&code, &CodeFormatterOptions { end_of_line: eol, ..Default::default() });
        assert!(r.code.contains(escaped));
    }
}

// ---- DeepRecursionTests ----

#[test]
fn format_returns_an_error_for_deep_recursion() {
    let mut code = String::from("public class ClassName \n{\n    private string field = \"1\"");
    for _ in 0..210 {
        code.push_str(" +\n    \"1\"");
    }
    code.push_str(";\n}");
    let r = format(&code);
    assert_eq!(r.failure_message, "We can't handle this deep of recursion yet.");
}
