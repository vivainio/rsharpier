//! Ported from CSharpFormatterTests, LineEndingTests and DeepRecursionTests

use csharpier_rs::api::{CSharpFormatter, CodeFormatterOptions, IndentStyle};
use csharpier_rs::doc::EndOfLine;

fn format(code: &str) -> csharpier_rs::api::CodeFormatterResult {
    CSharpFormatter::format(code, &CodeFormatterOptions::default())
}

#[test]
fn format_uses_default_width() {
    let r = format("var someVariable = someValue;");
    assert_eq!(r.code, "var someVariable = someValue;\n");
    assert!(r.error_diagnostics.is_empty());
}

#[test]
fn format_returns_compilation_errors() {
    let code = "var someVariable = someValue";
    let r = format(code);
    assert_eq!(r.code, code);
    assert_eq!(r.error_diagnostics.len(), 1);
}

#[test]
fn format_uses_width() {
    let r = CSharpFormatter::format(
        "var someVariable = someValue;",
        &CodeFormatterOptions { width: 10, ..Default::default() },
    );
    assert_eq!(r.code, "var someVariable =\n    someValue;\n");
}

